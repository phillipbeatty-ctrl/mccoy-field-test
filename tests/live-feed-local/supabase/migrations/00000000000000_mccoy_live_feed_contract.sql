create table public.sales_feed (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  sale_id uuid not null references public.sales_records(id) on delete cascade,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  rep_user_id uuid not null references public.users(id) on delete restrict,
  rep_name text not null,
  isp text not null,
  message text not null,
  celebration_types text[] not null default '{}'::text[],
  celebration_messages jsonb not null default '[]'::jsonb,

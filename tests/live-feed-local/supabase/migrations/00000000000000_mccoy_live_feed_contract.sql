  ranking_eligible_at_event boolean not null default false
);

create or replace function private.current_organization_id()
returns uuid
language sql
stable
security definer
set search_path = pg_catalog, public, auth
as $$
  select membership.organization_id
  from public.organization_memberships membership
  where membership.auth_user_id = auth.uid()
    and membership.active
  order by membership.is_default desc, membership.created_at asc
  limit 1
$$;

create or replace function private.mccoy_organization_id()
returns uuid
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select organization.id
  from public.organizations organization
  where organization.slug = 'mccoy-platform-llc'
  limit 1
$$;

create or replace function private.organization_access_allowed(
  p_organization_id uuid,
  p_entitlement text default 'field_coach_access'
)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1
    from public.organizations organization
    where organization.id = p_organization_id
      and organization.active
      and organization.billing_status in (
        'internal_unlimited',
        'trial_active',
        'active',
        'grace'
      )
      and p_entitlement = 'field_coach_access'
  )
$$;


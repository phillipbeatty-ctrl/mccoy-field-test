create or replace function private.apply_authoritative_sph(p_item jsonb,p_map jsonb)
returns jsonb
language plpgsql
immutable
set search_path = pg_catalog
as $function$
declare v_key text;v_metric jsonb;v_item jsonb:=p_item;
begin
  if coalesce((v_item->>'is_ghost')::boolean,false) then return v_item; end if;
  v_key:=lower(trim(coalesce(v_item->>'rep_name','')))||'|'||lower(trim(coalesce(v_item->>'role','')))||'|'||lower(trim(coalesce(v_item->>'team_name','')));
  v_metric:=p_map->v_key;
  if v_metric is null then return v_item; end if;
  v_item:=jsonb_set(v_item,'{sales_per_hour}',v_metric,true);
  v_item:=jsonb_set(v_item,'{ranks,sales_per_hour}',coalesce(v_metric->'rank','null'::jsonb),true);
  return v_item;
end;
$function$;
revoke all on function private.apply_authoritative_sph(jsonb,jsonb) from public,anon,authenticated,service_role;

create or replace function public.get_sph_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public, auth, private
as $function$
declare v_uid uuid:=(select auth.uid());v_home public.sph_rep_settings%rowtype;v_latest public.sph_presence_events%rowtype;v_access boolean;
begin
  if v_uid is null then raise exception 'authentication_required' using errcode='42501';end if;
  select exists(select 1 from auth.users au join public.app_user_access a on lower(trim(a.email))=lower(trim(au.email)) where au.id=v_uid and a.active) into v_access;
  if not v_access then raise exception 'active_mccoy_access_required' using errcode='42501';end if;
  select * into v_home from public.sph_rep_settings where user_id=v_uid;
  select * into v_latest from public.sph_presence_events where rep_user_id=v_uid and timezone('America/Los_Angeles',event_at)::date=timezone('America/Los_Angeles',clock_timestamp())::date order by event_at desc limit 1;
  return jsonb_build_object('ok',true,'home_configured',v_home.home_latitude is not null,'home_label',v_home.home_label,
    'today',jsonb_build_object('inside_area',v_latest.inside_area,'area_basis',coalesce(v_latest.area_basis,'none'),
      'last_sample_at',v_latest.event_at,'status_label',case when v_latest.id is null then 'Waiting for today''s authenticated workday sample'
       when v_latest.inside_area is true then 'In assigned area · Sales/Hour timer active'
       when v_latest.area_basis='none' then 'No assigned area detected · 11 AM–7 PM fallback applies'
       else 'Outside assigned area' end),
    'policy',jsonb_build_object('source','authenticated_mccoy_workday_area_model','start_in_area_local','13:00',
      'no_area_fallback_local','11:00-19:00','sunday_excluded',true,'lunch_hours',1,'outside_after_7pm_meters',402.336,'outbound_minutes',20));
end;
$function$;

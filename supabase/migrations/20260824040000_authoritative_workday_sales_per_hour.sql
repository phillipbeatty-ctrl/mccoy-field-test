-- Authoritative Sales/Hour workday model.
--
-- The denominator is independent of the Start/Stop Knocking button. McCoy
-- records consented, authenticated presence while the app is open and keeps a
-- server-owned daily window. Explicit field areas are preferred; assigned,
-- geocoded leads are the fallback area. Sunday is excluded and one lunch hour
-- is deducted per counted day.

create table if not exists public.sph_rep_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  home_label text,
  home_latitude double precision,
  home_longitude double precision,
  home_accuracy_meters double precision,
  updated_at timestamptz not null default clock_timestamp(),
  constraint sph_rep_settings_home_pair check (
    (home_latitude is null and home_longitude is null)
    or (home_latitude between -90 and 90 and home_longitude between -180 and 180)
  ),
  constraint sph_rep_settings_home_accuracy check (
    home_accuracy_meters is null or home_accuracy_meters between 0 and 100
  ),
  constraint sph_rep_settings_label_length check (
    home_label is null or char_length(home_label) between 1 and 200
  )
);

create table if not exists public.sph_presence_events (
  id bigint generated by default as identity primary key,
  rep_user_id uuid not null references auth.users(id) on delete cascade,
  event_at timestamptz not null default clock_timestamp(),
  event_type text not null,
  latitude double precision,
  longitude double precision,
  accuracy_meters double precision,
  inside_area boolean,
  distance_outside_area_m double precision,
  distance_home_m double precision,
  area_basis text not null default 'none',
  source_test_event_id bigint references public.test_events(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  constraint sph_presence_event_type_check check (
    event_type in ('login','heartbeat','sale','field_start','field_end','home_update','historical')
  ),
  constraint sph_presence_coordinate_pair check (
    (latitude is null and longitude is null)
    or (latitude between -90 and 90 and longitude between -180 and 180)
  ),
  constraint sph_presence_accuracy_check check (
    accuracy_meters is null or accuracy_meters between 0 and 10000
  ),
  constraint sph_presence_area_basis_check check (
    area_basis in ('explicit_assignment','assigned_leads','none','unverified_gps')
  )
);

create unique index if not exists sph_presence_source_test_event_uidx
  on public.sph_presence_events(source_test_event_id)
  where source_test_event_id is not null;
create index if not exists sph_presence_rep_time_idx
  on public.sph_presence_events(rep_user_id,event_at desc);
create index if not exists sph_presence_rep_inside_time_idx
  on public.sph_presence_events(rep_user_id,event_at)
  where inside_area is not null;

create table if not exists public.sph_home_setting_audit (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  changed_by uuid not null references auth.users(id),
  action text not null default 'home_location_updated',
  changed_at timestamptz not null default clock_timestamp(),
  constraint sph_home_setting_action_check check (action in ('home_location_updated','home_location_cleared'))
);
create index if not exists sph_home_setting_audit_user_time_idx
  on public.sph_home_setting_audit(user_id,changed_at desc);

alter table public.sph_rep_settings enable row level security;
alter table public.sph_presence_events enable row level security;
alter table public.sph_home_setting_audit enable row level security;
